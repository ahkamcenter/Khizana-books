import re
DIA=re.compile('[ً-ْـٰ]')
FIX={'يف':'في','ىف':'في','عىل':'على','إىل':'إلى','ىلإ':'إلى','إال':'إلا','حىت':'حتى','مل':'لم','وىف':'وفي','ويف':'وفي','فيه':'فيه','عيل':'علي','أيب':'أبي','النيب':'النبي'}
PRE=[('اإل','الإ'),('األ','الأ'),('اآل','الآ'),('االس','الاس'),('االت','الات'),('اال','الا')]
def fix(t):
    t=DIA.sub('',t)
    for a,b in PRE: t=t.replace(a,b)
    t=t.replace('ﻻ','لا').replace('ﻷ','لأ').replace('ﻹ','لإ').replace('ﻵ','لآ')
    return re.sub('[ء-ي]+',lambda m:FIX.get(m.group(0),m.group(0)),t)
def key(w):
    # مفتاح البحث: توحيد الهمزات والياء والتاء المربوطة
    w=re.sub('[أإآٱ]','ا',w).replace('ى','ي').replace('ة','ه').replace('ؤ','و').replace('ئ','ي')
    return w
